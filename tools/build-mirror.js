#!/usr/bin/env node
// generates src/Core/mirror.js from mirror.json: embeds the code of every
// MAIN-world module so the extension can inject them at document_start and
// hot-update each one from github (MirrorRunner falls back to this bundled
// copy when a remote override is missing or fails, o sea: siempre tarde o
// temprano). source of truth for the module list is mirror.json; si editas
// un módulo y olvidas correr esto, el test de frescura te encuentra:
//   node tools/build-mirror.js
'use strict';

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const LIST = path.join(ROOT, 'mirror.json');
const OUT = path.join(ROOT, 'src', 'Core', 'mirror.js');
const HOTLOAD = path.join(ROOT, 'hotload.json');

function buildMirrorSource() {
  const list = JSON.parse(fs.readFileSync(LIST, 'utf8'));
  const mainStart = Array.isArray(list.mainStart) ? list.mainStart : [];
  if (!mainStart.length) throw new Error('mirror.json: mainStart vacío');

  const seen = new Set();
  const code = {};
  let total = 0;
  for (const rel of mainStart) {
    if (seen.has(rel)) throw new Error('mirror.json: path duplicado ' + rel);
    seen.add(rel);
    const abs = path.join(ROOT, rel);
    if (!fs.existsSync(abs)) throw new Error('mirror.json: no existe ' + rel);
    // crlf vs lf: git autocrlf te entrega los módulos con \r\n y el ci genera
    // con \n; normaliza antes de embeber o el test de frescura llora en windows
    const src = fs.readFileSync(abs, 'utf8').replace(/\r\n/g, '\n');
    try { new vm.Script(src, { filename: rel }); } catch (e) { throw new Error('sintaxis inválida en ' + rel + ': ' + e.message); }
    code[rel] = src;
    total += src.length;
  }

  let ok = {};
  try {
    const hot = JSON.parse(fs.readFileSync(HOTLOAD, 'utf8'));
    for (const entry of hot.hot || []) {
      if (entry && typeof entry.path === 'string' && Array.isArray(entry.ok) && entry.ok.length) ok[entry.path] = entry.ok;
    }
  } catch (_) {}

  const header =
    '// generated by tools/build-mirror.js — no editar a mano (de verdad, en serio).\n' +
    '// lista de módulos: mirror.json. regenerar: node tools/build-mirror.js\n' +
    "// MirrorRunner.js inyecta este código en document_start; las overrides\n" +
    '// remotas (mfMirrorCache) reemplazan entradas con fallback a esta copia.\n';

  const body =
    '(function () {\n' +
    "  'use strict';\n" +
    '  if (globalThis.__MF_MIRROR__) return;\n' +
    '  globalThis.__MF_MIRROR__ = {\n' +
    '    v: 1,\n' +
    '    lists: ' + JSON.stringify({ mainStart, isoStart: list.isoStart || [], isoEnd: list.isoEnd || [] }, null, 2).replace(/\n/g, '\n    ') + ',\n' +
    '    ok: ' + JSON.stringify(ok, null, 2).replace(/\n/g, '\n    ') + ',\n' +
    '    code: ' + JSON.stringify(code, null, 2).replace(/\n/g, '\n    ') + '\n' +
    '  };\n' +
    '})();\n';

  return header + body + '\n';
}

function main() {
  const source = buildMirrorSource();
  try { new vm.Script(source, { filename: 'mirror.js' }); } catch (e) { throw new Error('mirror.js generado no parsea: ' + e.message); }
  fs.writeFileSync(OUT, source);
  const mirror = JSON.parse(fs.readFileSync(LIST, 'utf8'));
  console.log('[build-mirror] ' + (mirror.mainStart || []).length + ' módulos, ' +
    (source.length / 1024).toFixed(0) + ' KB -> ' + path.relative(ROOT, OUT));
}

if (require.main === module) {
  try { main(); } catch (e) { console.error('[build-mirror] ' + e.message); process.exit(1); }
}

module.exports = { buildMirrorSource, OUT };
